def bold(grid):
    """Smear right by one pixel: the classic bitmap bold (2px stems)."""
    out = []
    for row in grid:
        cells = [c == "#" for c in row] + [False]
        out.append("".join("#" if cells[i] or (i > 0 and cells[i - 1]) else "." for i in range(len(cells))))
    return out


def outline(grid, x0):
    """One rectangle per horizontal run of pixels."""
    pen = TTGlyphPen(None)
    for r, row in enumerate(grid):
        top = (9 - r) * PX
        c = 0
        while c < len(row):
            if row[c] != "#":
                c += 1
                continue
            start = c
            while c < len(row) and row[c] == "#":
                c += 1
            left, right = (x0 + start) * PX, (x0 + c) * PX
            pen.moveTo((left, top - PX)); pen.lineTo((left, top))
            pen.lineTo((right, top)); pen.lineTo((right, top - PX)); pen.closePath()
    return pen.glyph()


def build(path, family, variant, mono=None):
    names, cmap, glyphs, metrics = [".notdef"], {}, {}, {}
    box = ["#####"] + ["#...#"] * 7 + ["#####", ".....", "....."]
    glyphs[".notdef"], metrics[".notdef"] = outline(box, 1), (7 * PX, PX)
    for ch, grid in sorted(G.items()):
        if mono and len(grid[0]) in (4, 5):
            # VGA letters fill their cell: widen 4-5px skeletons by one column.
            mid = len(grid[0]) // 2 - (1 if len(grid[0]) == 4 else 0)
            grid = [row[:mid + 1] + row[mid:] for row in grid]
        grid = bold(grid) if variant != "thin" else grid
        width = len(grid[0])
        if mono:
            x0, advance = max(0, (mono - width) // 2), mono
        else:
            x0, advance = 0, width + 1
        name = "uni%04X" % ord(ch)
        names.append(name)
        cmap[ord(ch)] = name
        glyphs[name] = outline(grid, x0)
        metrics[name] = (advance * PX, x0 * PX)
    fb = FontBuilder(12 * PX, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=10 * PX, descent=-2 * PX)
    fb.setupNameTable({"familyName": family, "styleName": "Regular",
                       "copyright": "Drawn for BindCards by Mimezu (MIT)"})
    fb.setupOS2(sTypoAscender=10 * PX, sTypoDescender=-2 * PX, sTypoLineGap=0,
                usWinAscent=10 * PX, usWinDescent=2 * PX)
    fb.setupPost(isFixedPitch=1 if mono else 0)
    fb.save(path)


