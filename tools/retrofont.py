"""Builds BindCards' retro bitmap fonts (original glyphs, drawn for BindCards).

One hand-drawn 1px skeleton (cap 9, x-height 6, descender 2) yields:
  RetroSans.ttf  thin proportional  (Windows 3.1 dialog text)
  RetroBold.ttf  bold proportional  (Mac 1-bit, Windows 3.1 titles)
  RetroMono.ttf  bold 8px cells      (MS-DOS text mode)
Em = 12 pixel rows, so a font size of 12 * k UI pixels draws k-pixel dots.

    python -I tools/retrofont.py    (needs fontTools)
"""
import os
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

ROWS = 11          # 0-8 above the baseline (row 8 sits on it), 9-10 descend
PX = 100           # font units per pixel; em = 12 rows
G = {}


def glyph(chars, *rows, top=0):
    """rows start at `top`; missing rows are blank."""
    width = max(len(r) for r in rows) if rows else 0
    grid = ["." * width] * ROWS
    for i, r in enumerate(rows):
        grid[top + i] = r.ljust(width, ".")
    for ch in chars:
        G[ch] = grid


